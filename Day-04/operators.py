#relational operators/comparison operators
x=26
y=14
print(x>y,x<y,x>=y,x<=y,x==y,x!=y)

#conditional operators/logical operators
x=26
y=14
print(x>y and x<y)
print(x>y or x<y)
print(not(x>y and x<y))
print(not(x>y or x<y))

#bitwise operators and membership operators
x=45
y=4
print(x & y)
print(x | y)
print(x ^ y)
print(~x)
print(y<<2)
print(y>>2)